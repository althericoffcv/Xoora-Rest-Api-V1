/** Picks a sensible icon for a category label ("AI", "Random", "Search Tools"...). */
export function categoryIcon(label = '') {
  const l = label.toLowerCase();
  if (/\b(ai|ml|bot|chat)\b/.test(l)) return 'sparkles';
  if (l.includes('random')) return 'shuffle';
  if (l.includes('search')) return 'search';
  if (l.includes('image') || l.includes('photo')) return 'image';
  if (l.includes('tool') || l.includes('util')) return 'wrench';
  if (l.includes('download')) return 'arrow-down';
  return 'layers';
}

export function icon(name, { size = 20, className = '', stroke = 1.8, fill = false } = {}) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', size);
  svg.setAttribute('height', size);
  svg.setAttribute('fill', fill ? 'currentColor' : 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', stroke);
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('class', `icon${className ? ` ${className}` : ''}`);
  svg.innerHTML = PATHS[name] || PATHS.circle;
  return svg;
}
